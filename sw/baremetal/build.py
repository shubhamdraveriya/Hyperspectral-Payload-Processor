"""Build the bare-metal platform and applications with Vitis (2025.2).

    vitis -s sw/baremetal/build.py [path/to/hpdp.xsa]

The XSA defaults to build/hpdp.xsa (written by vivado/build.tcl). The workspace
is recreated from scratch in the repository's vitis/ folder (git-ignored), or at
HPDP_VITIS_WS if set. Vitis 2025.2 fails on paths with spaces (the repository
lives under "Linux Boot", docs/m0_bringup.md issue 3), so it sees vitis/ through
a directory junction without spaces, ~/hpdp_vitis_ws, created here if missing
(junctions need no administrator rights).
"""

import os
import shutil
import stat
import subprocess
import sys
from pathlib import Path

import vitis

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent

PLATFORM = "hpdp_platform"
DOMAIN = "standalone_a53_0"
CPU = "psu_cortexa53_0"
APPS = ["hpdp_run"]
COMMON = HERE / "common"         # shared headers (hpdp_regs.h, generated by regs/generate.py)
REPO_WS = REPO / "vitis"         # the workspace's files
LINK = Path.home() / "hpdp_vitis_ws"   # how Vitis sees them (no spaces)


def _remove_readonly(func, path, _exc):
    # Vitis leaves some generated files read-only, which rmtree cannot delete on Windows
    os.chmod(path, stat.S_IWRITE)
    func(path)


def _clear(folder):
    """empty a folder (not the folder itself: it may be a junction's target)"""
    for child in folder.iterdir():
        if child.is_dir() and not child.is_symlink():
            shutil.rmtree(child, onexc=_remove_readonly)
        else:
            child.unlink()


xsa = Path(sys.argv[1] if len(sys.argv) > 1 else REPO / "build" / "hpdp.xsa").resolve()
if not xsa.exists():
    sys.exit(f"XSA not found: {xsa} (run vivado/build.tcl first)")
if "HPDP_VITIS_WS" in os.environ:
    ws = Path(os.environ["HPDP_VITIS_WS"]).absolute()
    if " " in str(ws):
        sys.exit(f"workspace path contains a space: {ws}")
    if ws.exists():
        shutil.rmtree(ws, onexc=_remove_readonly)
else:
    REPO_WS.mkdir(exist_ok=True)
    if not os.path.lexists(LINK):
        subprocess.run(["cmd", "/c", "mklink", "/J", str(LINK), str(REPO_WS)], check=True,
                       capture_output=True)
    if os.path.realpath(LINK) != os.path.realpath(REPO_WS):
        sys.exit(f"{LINK} exists but does not lead to {REPO_WS}: remove it or set HPDP_VITIS_WS")
    if " " in str(LINK):
        sys.exit(f"junction path contains a space: {LINK} (set HPDP_VITIS_WS)")
    _clear(LINK)                 # through the junction: some BSP paths are too long under the
                                 # repository's own path (260-character limit)
    ws = LINK                    # not resolved: Vitis must see the path without spaces
print(f"workspace {ws}" + (f" (files in {REPO_WS})" if ws == LINK else ""))
client = vitis.create_client()
client.set_workspace(path=str(ws))

# Vitis cannot read an XSA from a path with spaces either: work on a copy
local_xsa = ws / "hpdp.xsa"
shutil.copy2(xsa, local_xsa)

platform = client.create_platform_component(
    name=PLATFORM, hw_design=str(local_xsa), os="standalone", cpu=CPU, domain_name=DOMAIN)

# lwIP for the ground record upload (hpdp_run/src/net.c, SW-05): raw API without
# an OS, settings of AMD's lwip_tcp_perf_server; xiltimer's interval timer
# drives the lwIP timers
LWIP = "lwip220"
LWIP_CONFIG = {
    "lwip220_api_mode": "RAW_API",
    "lwip220_dhcp": "true",
    "lwip220_lwip_dhcp_does_acd_check": "true",
    "lwip220_ipv6_enable": "false",
    "lwip220_mem_size": "524288",
    "lwip220_memp_n_pbuf": "1024",
    "lwip220_memp_n_tcp_seg": "1024",
    "lwip220_n_rx_descriptors": "512",
    "lwip220_n_tx_descriptors": "512",
    "lwip220_pbuf_pool_size": "16384",
    "lwip220_tcp_snd_buf": "65535",
    "lwip220_tcp_wnd": "65535",
}
domain = platform.get_domain(DOMAIN)
domain.set_lib(lib_name=LWIP)
for param, value in LWIP_CONFIG.items():
    domain.set_config(option="lib", param=param, value=value, lib_name=LWIP)
domain.set_config(option="lib", param="XILTIMER_en_interval_timer", value="true", lib_name="xiltimer")
# FatFs for the console's SD card loading (hpdp_run/src/console.c, SW-02): long
# file names (.hpdp is not an 8.3 name), read-only so the card is never written
domain.set_lib(lib_name="xilffs")
domain.set_config(option="lib", param="XILFFS_use_lfn", value="1", lib_name="xilffs")
domain.set_config(option="lib", param="XILFFS_read_only", value="true", lib_name="xilffs")
platform.build()
xpfm = ws / PLATFORM / "export" / PLATFORM / f"{PLATFORM}.xpfm"

for name in APPS:
    src = HERE / name / "src"
    app = client.create_app_component(name=name, platform=str(xpfm), domain=DOMAIN,
                                      template="empty_application")
    app.import_files(from_loc=str(src), files=sorted(p.name for p in src.iterdir()),
                     dest_dir_in_cmp="src")
    app.import_files(from_loc=str(COMMON), files=sorted(p.name for p in COMMON.iterdir()),
                     dest_dir_in_cmp="src")
    ld = app.get_ld_script()                    # lwIP and the Ethernet driver need more than 8 KB
    ld.set_stack_size("0x10000")
    ld.set_heap_size("0x10000")
    app.build()
    print(f"built {ws / name / 'build' / (name + '.elf')}")

vitis.dispose()
