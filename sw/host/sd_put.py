"""Write files to the ZCU106's SD card through the board, when no card reader is at
hand: the files and a manifest go into DDR over JTAG, sw/baremetal/sd_put writes
them to the card's root and reads them back. JTAG only (no flash); the PL is not
configured. Files of the same name on the card are replaced; nothing else is touched.

    python sw/host/sd_put.py data/sdcard/*  [--work sd_put] [--dry-run]

Build sd_put first: vitis -s sw/baremetal/build_sd_put.py
"""

import argparse
import struct
import subprocess
import sys
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import run_m4 as m4  # noqa: E402

REPO = Path(__file__).resolve().parents[2]
MANIFEST_ADDR, RESULT_ADDR, DATA_ADDR = 0x1000_0000, 0x1000_F000, 0x1100_0000
MANIFEST_MAGIC, RESULT_MAGIC, MAX_FILES = 0x54504453, 0x4B4F4453, 16
DEFAULT_ELF = Path.home() / "hpdp_sdput_ws" / "sd_put" / "build" / "sd_put.elf"


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("files", nargs="+")
    p.add_argument("--xsa", default=str(REPO / "build" / "m7h" / "hpdp.xsa"), help="for psu_init.tcl")
    p.add_argument("--elf", default=str(DEFAULT_ELF))
    p.add_argument("--work", default="sd_put")
    p.add_argument("--xsdb", default=str(m4.XSDB))
    p.add_argument("--timeout", type=int, default=600)
    p.add_argument("--dry-run", action="store_true")
    a = p.parse_args()

    files = [Path(f) for f in a.files]
    if not 0 < len(files) <= MAX_FILES:
        sys.exit(f"1 to {MAX_FILES} files")
    work = m4.work_dir(a.work)
    work.mkdir(parents=True, exist_ok=True)

    # data files, 64-byte aligned from DATA_ADDR; the manifest lists them
    manifest = struct.pack("<II", MANIFEST_MAGIC, len(files))
    loads, addr = [], DATA_ADDR
    for k, f in enumerate(files):
        name = f.name.encode("ascii")
        if len(name) > 55:
            sys.exit(f"{f.name}: name longer than 55 characters")
        size = f.stat().st_size
        (work / f"file{k}.bin").write_bytes(f.read_bytes())
        loads.append((f"file{k}.bin", addr))
        manifest += name.ljust(56, b"\0") + struct.pack("<II", addr, size)
        print(f"  {f.name}: {size} bytes at 0x{addr:08X}")
        addr = (addr + size + 63) & ~63
    if addr > 0x7000_0000:
        sys.exit("files too large for DDR")
    (work / "manifest.bin").write_bytes(manifest)

    with zipfile.ZipFile(Path(a.xsa).resolve()) as z:
        init = next(n for n in z.namelist() if n.endswith("psu_init.tcl"))
        (work / "psu_init.tcl").write_bytes(z.read(init))
    (work / "sd_put.elf").write_bytes(Path(a.elf).read_bytes())
    w = work.as_posix()
    data = "".join(f"dow -data {{{w}/{n}}} 0x{ad:08X}\n" for n, ad in loads)
    tcl = f"""# Generated by sw/host/sd_put.py. JTAG only: nothing here writes flash; the PL is not configured.
connect
targets -set -nocase -filter {{name =~ "PSU"}}
# boot mode JTAG until power-off, so the QSPI image does not start (docs/m0_bringup.md)
mwr 0xFF5E0200 0x0100
rst -system
after 2000
targets -set -nocase -filter {{name =~ "APU*"}}
source {{{w}/psu_init.tcl}}
psu_init
after 1000
targets -set -nocase -filter {{name =~ "*A53*#0"}}
rst -processor
{data}dow -data {{{w}/manifest.bin}} 0x{MANIFEST_ADDR:08X}
mwr 0x{RESULT_ADDR:08X} 0
dow {{{w}/sd_put.elf}}
con
targets -set -nocase -filter {{name =~ "PSU"}}
set t0 [clock seconds]
while {{1}} {{
    after 1000
    if {{[mrd -force -value 0x{RESULT_ADDR:08X}] == 0x{RESULT_MAGIC:08X}}} break
    if {{[clock seconds] - $t0 > {a.timeout}}} {{ error "no result after {a.timeout} s" }}
}}
mrd -force -bin -file {{{w}/result.bin}} 0x{RESULT_ADDR:08X} {4 + 2 * MAX_FILES}
puts "sd_put: result read back"
"""
    (work / "run.tcl").write_text(tcl, encoding="utf-8", newline="\n")
    print(f"XSDB script: {work / 'run.tcl'}")
    if a.dry_run:
        return 0
    print("running XSDB (JTAG): files into DDR, sd_put writes and verifies them ...")
    if subprocess.call([a.xsdb, str(work / "run.tcl")]) != 0:
        print("FAIL: XSDB reported an error")
        return 1
    r = struct.unpack(f"<{4 + 2 * MAX_FILES}I", (work / "result.bin").read_bytes())
    magic, status, ok, count = r[:4]
    fres, verified = r[4:4 + MAX_FILES], r[4 + MAX_FILES:]
    for k, f in enumerate(files):
        print(f"  {f.name}: " + ("written and verified" if verified[k] else f"FAILED (error {fres[k]})"))
    good = magic == RESULT_MAGIC and status == 0 and ok == len(files)
    print(("PASS" if good else "FAIL") + f": sd_put, {ok} of {len(files)} files on the SD card (status {status})")
    return 0 if good else 1


if __name__ == "__main__":
    sys.exit(main())
