"""Generate everything that depends on the register map (SPEC.md 8.3).

    python regs/generate.py [--html]

From regs/hpdp.rdl:
    rtl/regs/hpdp_regs.sv, hpdp_regs_pkg.sv   register block (PeakRDL-regblock, AXI4-Lite)
    sw/baremetal/common/hpdp_regs.h           C header (PeakRDL-cheader): field masks and
                                              positions; register offsets via offsetof()
    tb/system/hpdp_regs_addr_pkg.sv           register addresses for testbenches
    sw/host/hpdp_regs.py                      register and field addresses for host tools
    build/regs_html/                          HTML documentation (with --html)

The outputs are committed, so the RTL and software builds do not need PeakRDL.
Run this after every change to hpdp.rdl.
"""

import sys
from pathlib import Path

from peakrdl_cheader.exporter import CHeaderExporter
from peakrdl_regblock import RegblockExporter
from peakrdl_regblock.cpuif.axi4lite import AXI4Lite_Cpuif_flattened
from peakrdl_regblock.udps import ALL_UDPS
from systemrdl import RDLCompiler
from systemrdl.node import RegNode

REPO = Path(__file__).resolve().parents[1]
RDL = REPO / "regs" / "hpdp.rdl"
BASE = 0xA000_0000

HEADER = "Generated by regs/generate.py from regs/hpdp.rdl. Do not edit."


def registers(top):
    """(path, absolute offset, RegNode) for every register, path like 'se.LINE_PERIOD'."""
    out = []
    for node in top.descendants():
        if isinstance(node, RegNode):
            path = node.get_path().split(".", 1)[1]
            out.append((path, node.absolute_address, node))
    return out


def write_sv_addr(top, path):
    lines = [f"// {HEADER}", "package hpdp_regs_addr_pkg;", ""]
    lines.append(f"    localparam logic [31:0] HPDP_BASE = 32'h{BASE:08X};")
    for name, addr, _ in registers(top):
        lines.append(f"    localparam logic [31:0] {name.replace('.', '_').upper():32} = 32'h{addr:05X};")
    lines += ["", "endpackage", ""]
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def write_python(top, path):
    lines = [f'"""{HEADER}', "", "REGS: register path -> offset from BASE.",
             "FIELDS: field path -> (register offset, lsb, width).", '"""', "",
             f"BASE = 0x{BASE:08X}", "", "REGS = {"]
    fields = []
    for name, addr, reg in registers(top):
        lines.append(f'    "{name}": 0x{addr:05X},')
        for f in reg.fields():
            fields.append(f'    "{name}.{f.inst_name}": (0x{addr:05X}, {f.lsb}, {f.width}),')
    lines += ["}", "", "FIELDS = {"] + fields + ["}", ""]
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main():
    rdlc = RDLCompiler()
    for udp in ALL_UDPS:            # properties PeakRDL-regblock understands
        rdlc.register_udp(udp)
    rdlc.compile_file(str(RDL))
    top = rdlc.elaborate(top_def_name="hpdp_regs").top

    rtl = REPO / "rtl" / "regs"
    rtl.mkdir(parents=True, exist_ok=True)
    RegblockExporter().export(top, str(rtl), cpuif_cls=AXI4Lite_Cpuif_flattened,
                              module_name="hpdp_regs", package_name="hpdp_regs_pkg",
                              retime_read_response=True)

    hdr = REPO / "sw" / "baremetal" / "common" / "hpdp_regs.h"
    hdr.parent.mkdir(parents=True, exist_ok=True)
    CHeaderExporter().export(top, str(hdr))

    tb = REPO / "tb" / "system"
    tb.mkdir(parents=True, exist_ok=True)
    write_sv_addr(top, tb / "hpdp_regs_addr_pkg.sv")

    host = REPO / "sw" / "host"
    host.mkdir(parents=True, exist_ok=True)
    write_python(top, host / "hpdp_regs.py")

    if "--html" in sys.argv:
        from peakrdl_html import HTMLExporter
        HTMLExporter().export(top, str(REPO / "build" / "regs_html"))

    # PeakRDL writes the platform's line endings; keep the repository's LF
    for p in [rtl / "hpdp_regs.sv", rtl / "hpdp_regs_pkg.sv", hdr]:
        p.write_bytes(p.read_bytes().replace(b"\r\n", b"\n"))
    print(f"{len(registers(top))} registers generated")


if __name__ == "__main__":
    main()
